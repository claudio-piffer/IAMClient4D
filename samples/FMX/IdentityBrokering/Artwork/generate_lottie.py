"""Generates the Lottie animations of the mobile sample (spinner, success check).
Writes Artwork/Lottie/*.json and ../IdentityBrokeringMobile.Animations.pas (the JSON embedded as string constants).
Usage: python generate_lottie.py"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
INDIGO = [0x4F / 255, 0x46 / 255, 0xE5 / 255, 1]
TRACK = [0xE0 / 255, 0xE7 / 255, 0xFF / 255, 1]
GREEN = [0x22 / 255, 0xC5 / 255, 0x5E / 255, 1]
WHITE = [1, 1, 1, 1]


def static(v):
    return {"a": 0, "k": v}


def keys(*frames, ease=True):
    """Animated property: frames = (time, value). Smooth easing between keyframes."""
    out = []
    for i, (t, v) in enumerate(frames):
        k = {"t": t, "s": v if isinstance(v, list) else [v]}
        if i < len(frames) - 1:
            if ease:
                k["i"] = {"x": [0.4], "y": [1]}
                k["o"] = {"x": [0.6], "y": [0]}
            else:
                k["i"] = {"x": [1], "y": [1]}
                k["o"] = {"x": [0], "y": [0]}
        out.append(k)
    return {"a": 1, "k": out}


def transform():
    return {"ty": "tr", "p": static([0, 0]), "a": static([0, 0]), "s": static([100, 100]), "r": static(0),
            "o": static(100), "sk": static(0), "sa": static(0)}


def stroke(color, width):
    return {"ty": "st", "c": static(color), "o": static(100), "w": static(width), "lc": 2, "lj": 2}


def layer(index, name, shapes, ks_extra=None, op=90):
    ks = {"o": static(100), "r": static(0), "p": static([50, 50, 0]), "a": static([0, 0, 0]),
          "s": static([100, 100, 100])}
    ks.update(ks_extra or {})
    return {"ddd": 0, "ind": index, "ty": 4, "nm": name, "sr": 1, "ks": ks, "ao": 0, "shapes": shapes,
            "ip": 0, "op": op, "st": 0, "bm": 0}


def comp(name, frames, layers):
    return {"v": "5.7.0", "fr": 60, "ip": 0, "op": frames, "w": 100, "h": 100, "nm": name, "ddd": 0,
            "assets": [], "layers": layers}


def ellipse(size):
    return {"ty": "el", "p": static([0, 0]), "s": static([size, size]), "d": 1}


def spinner():
    arc = {"ty": "gr", "nm": "arc", "it": [
        ellipse(64),
        {"ty": "tm", "s": static(0), "e": keys((0, 12), (45, 72), (90, 12)), "o": static(0), "m": 1},
        stroke(INDIGO, 10), transform()]}
    track = {"ty": "gr", "nm": "track", "it": [ellipse(64), stroke(TRACK, 10), transform()]}
    rot = keys((0, 0), (90, 360), ease=False)
    return comp("spinner", 90, [layer(1, "spinner", [arc, track], {"r": rot})])


def success():
    check_path = {"ty": "sh", "ks": static({"i": [[0, 0], [0, 0], [0, 0]], "o": [[0, 0], [0, 0], [0, 0]],
                                              "v": [[-18, 1], [-6, 13], [19, -13]], "c": False})}
    check = {"ty": "gr", "nm": "check", "it": [
        check_path,
        {"ty": "tm", "s": static(0), "e": keys((20, 0), (38, 100)), "o": static(0), "m": 1},
        stroke(WHITE, 10), transform()]}
    disc = {"ty": "gr", "nm": "disc", "it": [
        ellipse(88), {"ty": "fl", "c": static(GREEN), "o": static(100), "r": 1}, transform()]}
    pop = keys((0, [0, 0, 100]), (16, [112, 112, 100]), (26, [100, 100, 100]))
    return comp("success", 60, [layer(1, "check", [check], op=60),
                                layer(2, "disc", [disc], {"s": pop}, op=60)])


def pascal_literal(name, text):
    chunks = [text[i:i + 110] for i in range(0, len(text), 110)]
    body = " +\n".join("  " + ("'" + c + "'") for c in chunks)
    return f"const\n  {name} =\n{body};\n"


def main():
    anims = {"Spinner": spinner(), "Success": success()}
    os.makedirs(os.path.join(HERE, "Lottie"), exist_ok=True)
    consts = []
    for name, data in anims.items():
        text = json.dumps(data, separators=(",", ":"))
        with open(os.path.join(HERE, "Lottie", name.lower() + ".json"), "w", newline="") as f:
            f.write(text)
        consts.append(pascal_literal("CLottie" + name, text))
    unit = f"""unit IdentityBrokeringMobile.Animations;

// Lottie animations of the mobile sample, embedded as JSON strings (generated by Artwork\\generate_lottie.py,
// the same animations are in Artwork\\Lottie). They are played by TSkAnimatedImage (Skia).

interface

uses
  FMX.Skia;

// Spinner: indigo arc that grows and shrinks while rotating on a light track (loops)
procedure LoadSpinner(const AImage: TSkAnimatedImage);
// Success check: green disc that pops, then the tick draws itself (plays once)
procedure LoadSuccess(const AImage: TSkAnimatedImage);

implementation

uses
  System.Classes,
  System.SysUtils;

{"".join(chr(10) + c for c in consts)}
procedure LoadJson(const AImage: TSkAnimatedImage; const AJson: string; const ALoop: Boolean);
var
  LStream: TStringStream;
begin
  LStream := TStringStream.Create(AJson, TEncoding.UTF8);
  try
    AImage.LoadFromStream(LStream);
  finally
    LStream.Free;
  end;
  AImage.Animation.Loop := ALoop;
end;

procedure LoadSpinner(const AImage: TSkAnimatedImage);
begin
  LoadJson(AImage, CLottieSpinner, True);
end;

procedure LoadSuccess(const AImage: TSkAnimatedImage);
begin
  LoadJson(AImage, CLottieSuccess, False);
end;

end.
"""
    with open(os.path.join(HERE, "..", "IdentityBrokeringMobile.Animations.pas"), "w", newline="") as f:
        f.write(unit.replace("\n", "\r\n"))


if __name__ == "__main__":
    main()
