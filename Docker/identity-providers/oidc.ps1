<#
  Creates or updates a generic OpenID Connect identity provider in the Keycloak of the samples (Docker/)
  (Admin REST API) from a discovery URL, with the same config as TIAM4DOidcIdPBuilder. The provider stays in
  the database of Docker/ until delete-volumes. For the test Keycloak (tests/IdentityProvider/docker,
  database in memory) run it after every up.cmd with -KeycloakUrl http://localhost:18080 -Realm iam4d-sample
  -AdminPassword admin.

  Keycloak downloads the discovery document itself: the URL must be reachable from the Keycloak container
  (another realm of this Keycloak: http://localhost:8080/realms/{realm}/.well-known/openid-configuration).
  Register a confidential client at the provider with redirect URI {KeycloakUrl}/realms/{Realm}/broker/{Alias}/endpoint
  (default http://localhost:18180/auth/realms/iamclient4d/broker/oidc/endpoint).

  Discovery URL, client ID and secret: parameters, otherwise OIDC_DISCOVERY_URL, OIDC_CLIENT_ID,
  OIDC_CLIENT_SECRET, otherwise asked (the secret without echo).

  Example:
    powershell -ExecutionPolicy Bypass -File oidc.ps1 -DiscoveryUrl https://idp.example.com/.well-known/openid-configuration -ClientId <client-id>
#>
param(
  [string]$DiscoveryUrl = $env:OIDC_DISCOVERY_URL,
  [string]$ClientId = $env:OIDC_CLIENT_ID,
  [string]$ClientSecret = $env:OIDC_CLIENT_SECRET,
  [string]$KeycloakUrl = $(if ($env:KC_PORT) { "http://localhost:$env:KC_PORT/auth" } else { 'http://localhost:18180/auth' }),
  [string]$Realm = 'iamclient4d',
  [string]$AdminUser = 'admin',
  # Default: the password generated by Docker/setup-secrets
  [string]$AdminPassword = $(Get-Content -Raw -ErrorAction SilentlyContinue (Join-Path $PSScriptRoot '../secrets/kc_admin_password.txt')),
  [string]$Alias = 'oidc',
  [string]$DisplayName = '',
  # Client authentication at the token endpoint
  [ValidateSet('client_secret_post', 'client_secret_basic')]
  [string]$ClientAuthMethod = 'client_secret_post',
  # Prompt sent to the provider, e.g. login or select_account
  [string]$Prompt = '',
  # Emails from the provider considered verified (the issuer is always checked)
  [switch]$TrustEmail,
  # Reachable only through kc_idp_hint
  [switch]$HideOnLogin
)
$ErrorActionPreference = 'Stop'

if (-not $DiscoveryUrl) { $DiscoveryUrl = Read-Host 'Discovery URL (as Keycloak reaches it)' }
if (-not $ClientId) { $ClientId = Read-Host 'Client ID' }
if (-not $ClientSecret) {
  $LSecure = Read-Host 'Client secret' -AsSecureString
  $ClientSecret = [Runtime.InteropServices.Marshal]::PtrToStringBSTR(
    [Runtime.InteropServices.Marshal]::SecureStringToBSTR($LSecure))
}
$DiscoveryUrl = $DiscoveryUrl.Trim()
$ClientId = $ClientId.Trim()
if (-not $DiscoveryUrl -or -not $ClientId -or -not $ClientSecret) { throw 'Discovery URL, client ID and client secret are required' }
if ($Alias -notmatch '^[A-Za-z0-9._\-]+$') { throw "Invalid alias '$Alias'" }

$Token = (Invoke-RestMethod -Method Post -Uri "$KeycloakUrl/realms/master/protocol/openid-connect/token" -Body @{
  client_id = 'admin-cli'; username = $AdminUser; password = $AdminPassword; grant_type = 'password'
}).access_token
$Headers = @{ Authorization = "Bearer $Token" }
$Admin = "$KeycloakUrl/admin/realms/$Realm/identity-provider"

# Keycloak reads the discovery document and returns the config it derives from it
$ImportBody = [Text.Encoding]::UTF8.GetBytes((@{ providerId = 'oidc'; fromUrl = $DiscoveryUrl } | ConvertTo-Json))
$Imported = Invoke-RestMethod -Method Post -Uri "$Admin/import-config" -Headers $Headers -ContentType 'application/json' -Body $ImportBody
# Same checks as TIAM4DOidcIdPBuilder.Build: without them Keycloak accepts tokens of any issuer or unsigned
if (-not $Imported.issuer) { throw 'The discovery document has no issuer' }
if (-not $Imported.jwksUrl) { throw 'The discovery document has no jwks_uri' }

$Config = [ordered]@{}
# Only the provider side: client and security settings are set here
foreach ($Key in 'authorizationUrl', 'tokenUrl', 'userInfoUrl', 'jwksUrl', 'logoutUrl', 'issuer', 'tokenIntrospectionUrl',
                 'metadataDescriptorUrl') {
  if ($Imported.$Key) { $Config[$Key] = $Imported.$Key }
}
$Config.clientId = $ClientId
$Config.clientSecret = $ClientSecret
$Config.clientAuthMethod = $ClientAuthMethod
$Config.defaultScope = 'openid profile email'
$Config.validateSignature = 'true'
$Config.useJwksUrl = 'true'
$Config.pkceEnabled = 'true'
$Config.pkceMethod = 'S256'
$Config.syncMode = 'IMPORT'
$Config.hideOnLogin = $HideOnLogin.IsPresent.ToString().ToLower()
if ($Prompt) { $Config.prompt = $Prompt.Trim() }

$Provider = [ordered]@{
  alias       = $Alias
  displayName = $DisplayName
  providerId  = 'oidc'
  enabled     = $true
  trustEmail  = $TrustEmail.IsPresent
  hideOnLogin = $HideOnLogin.IsPresent
  config      = $Config
}
$Instances = "$Admin/instances"
$Body = [Text.Encoding]::UTF8.GetBytes(($Provider | ConvertTo-Json -Depth 5))

$Exists = @(Invoke-RestMethod -Uri $Instances -Headers $Headers | Where-Object { $_.alias -eq $Alias }).Count -gt 0
if ($Exists) {
  Invoke-RestMethod -Method Put -Uri "$Instances/$Alias" -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' updated (issuer $($Imported.issuer))."
} else {
  Invoke-RestMethod -Method Post -Uri $Instances -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' created (issuer $($Imported.issuer))."
}
Write-Host "Redirect URI to register at the provider: $KeycloakUrl/realms/$Realm/broker/$Alias/endpoint"
