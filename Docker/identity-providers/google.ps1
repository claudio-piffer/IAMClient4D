<#
  Creates or updates the Google identity provider in the Keycloak of the samples (Docker/) (Admin REST API),
  with the same config as TIAM4DGoogleIdPBuilder. The provider stays in the database of Docker/ until
  delete-volumes. For the test Keycloak (tests/IdentityProvider/docker, database in memory) run it after
  every up.cmd with -KeycloakUrl http://localhost:18080 -Realm iam4d-sample -AdminPassword admin.

  Google Cloud console, APIs & Services > Credentials: OAuth client ID of type "Web application" with
  authorized redirect URI {KeycloakUrl}/realms/{Realm}/broker/{Alias}/endpoint
  (default http://localhost:18180/auth/realms/iamclient4d/broker/google/endpoint; Google accepts http for localhost).
  OAuth consent screen: while in "Testing" only the listed test users can log in.

  Client ID and secret: parameters, otherwise GOOGLE_CLIENT_ID, GOOGLE_CLIENT_SECRET, otherwise asked
  (the secret without echo).

  Example:
    powershell -ExecutionPolicy Bypass -File google.ps1 -ClientId <client-id> -HostedDomain example.com
#>
param(
  [string]$ClientId = $env:GOOGLE_CLIENT_ID,
  [string]$ClientSecret = $env:GOOGLE_CLIENT_SECRET,
  [string]$KeycloakUrl = $(if ($env:KC_PORT) { "http://localhost:$env:KC_PORT/auth" } else { 'http://localhost:18180/auth' }),
  [string]$Realm = 'iamclient4d',
  [string]$AdminUser = 'admin',
  # Default: the password generated by Docker/setup-secrets
  [string]$AdminPassword = $(Get-Content -Raw -ErrorAction SilentlyContinue (Join-Path $PSScriptRoot '../secrets/kc_admin_password.txt')),
  [string]$Alias = 'google',
  [string]$DisplayName = 'Google',
  # Google Workspace domains allowed to log in (claim hd); none: any Google account
  [string[]]$HostedDomain = @(),
  # Prompt sent to Google, e.g. select_account
  [string]$Prompt = '',
  # Emails from Google considered verified
  [switch]$TrustEmail,
  # Reachable only through kc_idp_hint
  [switch]$HideOnLogin
)
$ErrorActionPreference = 'Stop'

if (-not $ClientId) { $ClientId = Read-Host 'Client ID' }
if (-not $ClientSecret) {
  $LSecure = Read-Host 'Client secret' -AsSecureString
  $ClientSecret = [Runtime.InteropServices.Marshal]::PtrToStringBSTR(
    [Runtime.InteropServices.Marshal]::SecureStringToBSTR($LSecure))
}
$ClientId = $ClientId.Trim()
if (-not $ClientId -or -not $ClientSecret) { throw 'Client ID and client secret are required' }
# Keycloak splits on the comma and compares each entry as is with the hd claim (lower case)
$Domains = @($HostedDomain | ForEach-Object { $_ -split ',' } | ForEach-Object { $_.Trim().ToLower() } | Where-Object { $_ })
foreach ($D in $Domains) { if ($D -notmatch '^[a-z0-9\-]+(\.[a-z0-9\-]+)+$') { throw "Invalid hosted domain '$D'" } }

$Config = [ordered]@{
  clientId     = $ClientId
  clientSecret = $ClientSecret
  defaultScope = 'openid profile email'
  pkceEnabled  = 'true'
  pkceMethod   = 'S256'
  syncMode     = 'IMPORT'
  hideOnLogin  = $HideOnLogin.IsPresent.ToString().ToLower()
}
if ($Domains.Count -gt 0) { $Config.hostedDomain = $Domains -join ',' }
if ($Prompt) { $Config.prompt = $Prompt.Trim() }

$Provider = [ordered]@{
  alias       = $Alias
  displayName = $DisplayName
  providerId  = 'google'
  enabled     = $true
  trustEmail  = $TrustEmail.IsPresent
  hideOnLogin = $HideOnLogin.IsPresent
  config      = $Config
}

$Token = (Invoke-RestMethod -Method Post -Uri "$KeycloakUrl/realms/master/protocol/openid-connect/token" -Body @{
  client_id = 'admin-cli'; username = $AdminUser; password = $AdminPassword; grant_type = 'password'
}).access_token
$Headers = @{ Authorization = "Bearer $Token" }
$Instances = "$KeycloakUrl/admin/realms/$Realm/identity-provider/instances"
$Body = [Text.Encoding]::UTF8.GetBytes(($Provider | ConvertTo-Json -Depth 5))

$Exists = @(Invoke-RestMethod -Uri $Instances -Headers $Headers | Where-Object { $_.alias -eq $Alias }).Count -gt 0
if ($Exists) {
  Invoke-RestMethod -Method Put -Uri "$Instances/$Alias" -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' updated."
} else {
  Invoke-RestMethod -Method Post -Uri $Instances -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' created."
}
Write-Host "Authorized redirect URI to register in Google: $KeycloakUrl/realms/$Realm/broker/$Alias/endpoint"
