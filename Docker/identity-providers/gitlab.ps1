<#
  Creates or updates the GitLab identity provider (gitlab.com only: Keycloak has its endpoints hard-coded)
  in the Keycloak of the samples (Docker/) (Admin REST API), with the same config as TIAM4DGitLabIdPBuilder:
  id_token signature and issuer checked with the keys of gitlab.com. The provider stays in the database of
  Docker/ until delete-volumes. For the test Keycloak (tests/IdentityProvider/docker, database in memory)
  run it after every up.cmd with -KeycloakUrl http://localhost:18080 -Realm iam4d-sample -AdminPassword
  admin. For a self-managed GitLab use oidc.ps1 with {GitLab}/.well-known/openid-configuration.

  gitlab.com, User settings > Applications > Add new application: redirect URI
  {KeycloakUrl}/realms/{Realm}/broker/{Alias}/endpoint (default
  http://localhost:18180/auth/realms/iamclient4d/broker/gitlab/endpoint), Confidential, scopes openid, read_user
  and email; Application ID and Secret are client ID and secret.

  Client ID and secret: parameters, otherwise GITLAB_CLIENT_ID, GITLAB_CLIENT_SECRET, otherwise asked
  (the secret without echo).

  Example:
    powershell -ExecutionPolicy Bypass -File gitlab.ps1 -ClientId <application-id> -TrustEmail
#>
param(
  [string]$ClientId = $env:GITLAB_CLIENT_ID,
  [string]$ClientSecret = $env:GITLAB_CLIENT_SECRET,
  [string]$KeycloakUrl = $(if ($env:KC_PORT) { "http://localhost:$env:KC_PORT/auth" } else { 'http://localhost:18180/auth' }),
  [string]$Realm = 'iamclient4d',
  [string]$AdminUser = 'admin',
  # Default: the password generated by Docker/setup-secrets
  [string]$AdminPassword = $(Get-Content -Raw -ErrorAction SilentlyContinue (Join-Path $PSScriptRoot '../secrets/kc_admin_password.txt')),
  [string]$Alias = 'gitlab',
  [string]$DisplayName = 'GitLab',
  # Emails considered verified: Keycloak reads email_verified from the GitLab id_token (email scope)
  [switch]$TrustEmail,
  # Reachable only through kc_idp_hint
  [switch]$HideOnLogin
)
$ErrorActionPreference = 'Stop'

if (-not $ClientId) { $ClientId = Read-Host 'Client ID' }
if (-not $ClientSecret) {
  $LSecure = Read-Host 'Client secret' -AsSecureString
  $ClientSecret = [Runtime.InteropServices.Marshal]::PtrToStringBSTR(
    [Runtime.InteropServices.Marshal]::SecureStringToBSTR($LSecure))
}
$ClientId = $ClientId.Trim()
if (-not $ClientId -or -not $ClientSecret) { throw 'Client ID and client secret are required' }
if ($Alias -notmatch '^[A-Za-z0-9._\-]+$') { throw "Invalid alias '$Alias'" }

$Config = [ordered]@{
  clientId          = $ClientId
  clientSecret      = $ClientSecret
  defaultScope      = 'openid read_user email'
  issuer            = 'https://gitlab.com'
  jwksUrl           = 'https://gitlab.com/oauth/discovery/keys'
  useJwksUrl        = 'true'
  validateSignature = 'true'
  pkceEnabled       = 'true'
  pkceMethod        = 'S256'
  syncMode          = 'IMPORT'
  hideOnLogin       = $HideOnLogin.IsPresent.ToString().ToLower()
}

$Provider = [ordered]@{
  alias       = $Alias
  displayName = $DisplayName
  providerId  = 'gitlab'
  enabled     = $true
  trustEmail  = $TrustEmail.IsPresent
  hideOnLogin = $HideOnLogin.IsPresent
  config      = $Config
}

$Token = (Invoke-RestMethod -Method Post -Uri "$KeycloakUrl/realms/master/protocol/openid-connect/token" -Body @{
  client_id = 'admin-cli'; username = $AdminUser; password = $AdminPassword; grant_type = 'password'
}).access_token
$Headers = @{ Authorization = "Bearer $Token" }
$Instances = "$KeycloakUrl/admin/realms/$Realm/identity-provider/instances"
$Body = [Text.Encoding]::UTF8.GetBytes(($Provider | ConvertTo-Json -Depth 5))

$Exists = @(Invoke-RestMethod -Uri $Instances -Headers $Headers | Where-Object { $_.alias -eq $Alias }).Count -gt 0
if ($Exists) {
  Invoke-RestMethod -Method Put -Uri "$Instances/$Alias" -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' updated."
} else {
  Invoke-RestMethod -Method Post -Uri $Instances -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' created."
}
Write-Host "Redirect URI to register in GitLab: $KeycloakUrl/realms/$Realm/broker/$Alias/endpoint"
