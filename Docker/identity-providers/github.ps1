<#
  Creates or updates the GitHub identity provider (github.com or GitHub Enterprise Server) in the Keycloak
  of the samples (Docker/) (Admin REST API), with the same config as TIAM4DGitHubIdPBuilder. The provider
  stays in the database of Docker/ until delete-volumes. For the test Keycloak
  (tests/IdentityProvider/docker, database in memory) run it after every up.cmd with -KeycloakUrl
  http://localhost:18080 -Realm iam4d-sample -AdminPassword admin.

  GitHub, Settings > Developer settings > OAuth Apps > New OAuth App: authorization callback URL
  {KeycloakUrl}/realms/{Realm}/broker/{Alias}/endpoint (default
  http://localhost:18180/auth/realms/iamclient4d/broker/github/endpoint), then Generate a new client secret.
  No trust email: Keycloak takes the GitHub email whether verified or not.

  Client ID and secret: parameters, otherwise GITHUB_CLIENT_ID, GITHUB_CLIENT_SECRET, otherwise asked
  (the secret without echo).

  Examples:
    powershell -ExecutionPolicy Bypass -File github.ps1 -ClientId <client-id>
    powershell -ExecutionPolicy Bypass -File github.ps1 -ClientId <client-id> -BaseUrl https://github.example.com `
      -ApiUrl https://github.example.com/api/v3
#>
param(
  [string]$ClientId = $env:GITHUB_CLIENT_ID,
  [string]$ClientSecret = $env:GITHUB_CLIENT_SECRET,
  [string]$KeycloakUrl = $(if ($env:KC_PORT) { "http://localhost:$env:KC_PORT/auth" } else { 'http://localhost:18180/auth' }),
  [string]$Realm = 'iamclient4d',
  [string]$AdminUser = 'admin',
  # Default: the password generated by Docker/setup-secrets
  [string]$AdminPassword = $(Get-Content -Raw -ErrorAction SilentlyContinue (Join-Path $PSScriptRoot '../secrets/kc_admin_password.txt')),
  [string]$Alias = 'github',
  [string]$DisplayName = 'GitHub',
  # GitHub Enterprise Server: web and API URLs, both or none
  [string]$BaseUrl = '',
  [string]$ApiUrl = '',
  # Reachable only through kc_idp_hint
  [switch]$HideOnLogin
)
$ErrorActionPreference = 'Stop'
# Not offered, as in TIAM4DGitHubIdPBuilder
$TrustEmail = [switch]::new($false)

if (-not $ClientId) { $ClientId = Read-Host 'Client ID' }
if (-not $ClientSecret) {
  $LSecure = Read-Host 'Client secret' -AsSecureString
  $ClientSecret = [Runtime.InteropServices.Marshal]::PtrToStringBSTR(
    [Runtime.InteropServices.Marshal]::SecureStringToBSTR($LSecure))
}
$ClientId = $ClientId.Trim()
if (-not $ClientId -or -not $ClientSecret) { throw 'Client ID and client secret are required' }
if ($Alias -notmatch '^[A-Za-z0-9._\-]+$') { throw "Invalid alias '$Alias'" }
$BaseUrl = $BaseUrl.Trim().TrimEnd('/')
$ApiUrl = $ApiUrl.Trim().TrimEnd('/')
if ([bool]$BaseUrl -ne [bool]$ApiUrl) { throw 'GitHub Enterprise: both -BaseUrl and -ApiUrl are required' }
foreach ($U in @($BaseUrl, $ApiUrl) | Where-Object { $_ }) {
  if ($U -notmatch '^https://[^/?#\s]+(/[^?#\s]*)?$') { throw "GitHub Enterprise: '$U' is not an https URL" }
}

$Config = [ordered]@{
  clientId     = $ClientId
  clientSecret = $ClientSecret
  defaultScope = 'user:email'
  pkceEnabled  = 'true'
  pkceMethod   = 'S256'
  syncMode     = 'IMPORT'
  hideOnLogin  = $HideOnLogin.IsPresent.ToString().ToLower()
}
if ($BaseUrl) { $Config.baseUrl = $BaseUrl; $Config.apiUrl = $ApiUrl }

$Provider = [ordered]@{
  alias       = $Alias
  displayName = $DisplayName
  providerId  = 'github'
  enabled     = $true
  trustEmail  = $TrustEmail.IsPresent
  hideOnLogin = $HideOnLogin.IsPresent
  config      = $Config
}

$Token = (Invoke-RestMethod -Method Post -Uri "$KeycloakUrl/realms/master/protocol/openid-connect/token" -Body @{
  client_id = 'admin-cli'; username = $AdminUser; password = $AdminPassword; grant_type = 'password'
}).access_token
$Headers = @{ Authorization = "Bearer $Token" }
$Instances = "$KeycloakUrl/admin/realms/$Realm/identity-provider/instances"
$Body = [Text.Encoding]::UTF8.GetBytes(($Provider | ConvertTo-Json -Depth 5))

$Exists = @(Invoke-RestMethod -Uri $Instances -Headers $Headers | Where-Object { $_.alias -eq $Alias }).Count -gt 0
if ($Exists) {
  Invoke-RestMethod -Method Put -Uri "$Instances/$Alias" -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' updated."
} else {
  Invoke-RestMethod -Method Post -Uri $Instances -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' created."
}
Write-Host "Authorization callback URL to register in GitHub: $KeycloakUrl/realms/$Realm/broker/$Alias/endpoint"
