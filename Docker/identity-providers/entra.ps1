<#
  Creates or updates the Microsoft Entra ID identity provider in the Keycloak of the samples (Docker/)
  (Admin REST API), with the same config as TIAM4DEntraIdPBuilder. The provider stays in the database of
  Docker/ until delete-volumes. For the test Keycloak (tests/IdentityProvider/docker, database in memory)
  run it after every up.cmd with -KeycloakUrl http://localhost:18080 -Realm iam4d-sample -AdminPassword
  admin.

  Entra ID app registration: redirect URI of type Web {KeycloakUrl}/realms/{Realm}/broker/{Alias}/endpoint
  (default http://localhost:18180/auth/realms/iamclient4d/broker/entra/endpoint) and a client secret.

  Tenant, client ID and secret: parameters, otherwise ENTRA_TENANT, ENTRA_CLIENT_ID, ENTRA_CLIENT_SECRET,
  otherwise asked (the secret without echo).

  Example:
    powershell -ExecutionPolicy Bypass -File entra.ps1 -Tenant <directory-id> -ClientId <application-id>
#>
param(
  [string]$Tenant = $env:ENTRA_TENANT,
  [string]$ClientId = $env:ENTRA_CLIENT_ID,
  [string]$ClientSecret = $env:ENTRA_CLIENT_SECRET,
  [string]$KeycloakUrl = $(if ($env:KC_PORT) { "http://localhost:$env:KC_PORT/auth" } else { 'http://localhost:18180/auth' }),
  [string]$Realm = 'iamclient4d',
  [string]$AdminUser = 'admin',
  # Default: the password generated by Docker/setup-secrets
  [string]$AdminPassword = $(Get-Content -Raw -ErrorAction SilentlyContinue (Join-Path $PSScriptRoot '../secrets/kc_admin_password.txt')),
  [string]$Alias = 'entra',
  [string]$DisplayName = 'Microsoft',
  # Emails from Entra ID considered verified: only with the directory ID (GUID) as tenant (nOAuth)
  [switch]$TrustEmail,
  # Reachable only through kc_idp_hint
  [switch]$HideOnLogin
)
$ErrorActionPreference = 'Stop'

if (-not $Tenant) { $Tenant = Read-Host 'Tenant (directory ID, domain or organizations)' }
if (-not $ClientId) { $ClientId = Read-Host 'Application (client) ID' }
if (-not $ClientSecret) {
  $LSecure = Read-Host 'Client secret' -AsSecureString
  $ClientSecret = [Runtime.InteropServices.Marshal]::PtrToStringBSTR(
    [Runtime.InteropServices.Marshal]::SecureStringToBSTR($LSecure))
}
$Tenant = $Tenant.Trim()
$ClientId = $ClientId.Trim()
if (-not $Tenant -or -not $ClientId -or -not $ClientSecret) { throw 'Tenant, client ID and client secret are required' }
if ($Tenant -notmatch '^[A-Za-z0-9.\-]+$') { throw "Invalid tenant '$Tenant'" }
$IsDirectoryID = $Tenant -match '^[0-9A-Fa-f]{8}-([0-9A-Fa-f]{4}-){3}[0-9A-Fa-f]{12}$'
if ($TrustEmail -and -not $IsDirectoryID) { throw 'TrustEmail requires the directory ID (GUID) as tenant' }

$Base = "https://login.microsoftonline.com/$Tenant"
$Config = [ordered]@{
  clientId          = $ClientId
  clientSecret      = $ClientSecret
  authorizationUrl  = "$Base/oauth2/v2.0/authorize"
  tokenUrl          = "$Base/oauth2/v2.0/token"
  logoutUrl         = "$Base/oauth2/v2.0/logout"
  jwksUrl           = "$Base/discovery/v2.0/keys"
  userInfoUrl       = 'https://graph.microsoft.com/oidc/userinfo'
  clientAuthMethod  = 'client_secret_post'
  defaultScope      = 'openid profile email'
  validateSignature = 'true'
  useJwksUrl        = 'true'
  pkceEnabled       = 'true'
  pkceMethod        = 'S256'
  syncMode          = 'IMPORT'
  hideOnLogin       = $HideOnLogin.IsPresent.ToString().ToLower()
}
# Tokens carry the directory ID: the issuer is known only when the tenant is that ID
if ($IsDirectoryID) { $Config.issuer = "$Base/v2.0" }

$Provider = [ordered]@{
  alias       = $Alias
  displayName = $DisplayName
  providerId  = 'oidc'
  enabled     = $true
  trustEmail  = $TrustEmail.IsPresent
  hideOnLogin = $HideOnLogin.IsPresent
  config      = $Config
}

$Token = (Invoke-RestMethod -Method Post -Uri "$KeycloakUrl/realms/master/protocol/openid-connect/token" -Body @{
  client_id = 'admin-cli'; username = $AdminUser; password = $AdminPassword; grant_type = 'password'
}).access_token
$Headers = @{ Authorization = "Bearer $Token" }
$Instances = "$KeycloakUrl/admin/realms/$Realm/identity-provider/instances"
$Body = [Text.Encoding]::UTF8.GetBytes(($Provider | ConvertTo-Json -Depth 5))

$Exists = @(Invoke-RestMethod -Uri $Instances -Headers $Headers | Where-Object { $_.alias -eq $Alias }).Count -gt 0
if ($Exists) {
  Invoke-RestMethod -Method Put -Uri "$Instances/$Alias" -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' updated."
} else {
  Invoke-RestMethod -Method Post -Uri $Instances -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' created."
}
Write-Host "Redirect URI to register in Entra ID (type Web): $KeycloakUrl/realms/$Realm/broker/$Alias/endpoint"
