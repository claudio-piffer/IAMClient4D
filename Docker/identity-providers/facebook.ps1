<#
  Creates or updates the Facebook identity provider in the Keycloak of the samples (Docker/) (Admin REST
  API), with the same config as TIAM4DFacebookIdPBuilder. The provider stays in the database of Docker/
  until delete-volumes. For the test Keycloak (tests/IdentityProvider/docker, database in memory) run it
  after every up.cmd with -KeycloakUrl http://localhost:18080 -Realm iam4d-sample -AdminPassword admin.

  Meta for Developers: app with the Facebook Login product, valid OAuth redirect URI
  {KeycloakUrl}/realms/{Realm}/broker/{Alias}/endpoint
  (default http://localhost:18180/auth/realms/iamclient4d/broker/facebook/endpoint; localhost works while the app
  is in development mode, where only users with a role in the app can log in).

  App ID and app secret: parameters, otherwise FACEBOOK_APP_ID, FACEBOOK_APP_SECRET, otherwise asked
  (the secret without echo).

  Example:
    powershell -ExecutionPolicy Bypass -File facebook.ps1 -AppId <app-id>
#>
param(
  [string]$AppId = $env:FACEBOOK_APP_ID,
  [string]$AppSecret = $env:FACEBOOK_APP_SECRET,
  [string]$KeycloakUrl = $(if ($env:KC_PORT) { "http://localhost:$env:KC_PORT/auth" } else { 'http://localhost:18180/auth' }),
  [string]$Realm = 'iamclient4d',
  [string]$AdminUser = 'admin',
  # Default: the password generated by Docker/setup-secrets
  [string]$AdminPassword = $(Get-Content -Raw -ErrorAction SilentlyContinue (Join-Path $PSScriptRoot '../secrets/kc_admin_password.txt')),
  [string]$Alias = 'facebook',
  [string]$DisplayName = 'Facebook',
  # Graph API profile fields besides id, name, email, first_name and last_name (e.g. birthday)
  [string[]]$FetchedFields = @(),
  # Emails from Facebook considered verified: Meta does not state it, keep it off unless accepted
  [switch]$TrustEmail,
  # Reachable only through kc_idp_hint
  [switch]$HideOnLogin
)
$ErrorActionPreference = 'Stop'

if (-not $AppId) { $AppId = Read-Host 'App ID' }
if (-not $AppSecret) {
  $LSecure = Read-Host 'App secret' -AsSecureString
  $AppSecret = [Runtime.InteropServices.Marshal]::PtrToStringBSTR(
    [Runtime.InteropServices.Marshal]::SecureStringToBSTR($LSecure))
}
$AppId = $AppId.Trim()
if (-not $AppId -or -not $AppSecret) { throw 'App ID and app secret are required' }
# Keycloak appends the list to the fields parameter of the Graph API URL as is
$Fields = @($FetchedFields | ForEach-Object { $_.Trim() } | Where-Object { $_ })
foreach ($F in $Fields) { if ($F -notmatch '^[A-Za-z0-9_.(){},]+$') { throw "Invalid fetched field '$F'" } }

$Config = [ordered]@{
  clientId     = $AppId
  clientSecret = $AppSecret
  defaultScope = 'email public_profile'
  syncMode     = 'IMPORT'
  hideOnLogin  = $HideOnLogin.IsPresent.ToString().ToLower()
}
if ($Fields.Count -gt 0) { $Config.fetchedFields = $Fields -join ',' }

$Provider = [ordered]@{
  alias       = $Alias
  displayName = $DisplayName
  providerId  = 'facebook'
  enabled     = $true
  trustEmail  = $TrustEmail.IsPresent
  hideOnLogin = $HideOnLogin.IsPresent
  config      = $Config
}

$Token = (Invoke-RestMethod -Method Post -Uri "$KeycloakUrl/realms/master/protocol/openid-connect/token" -Body @{
  client_id = 'admin-cli'; username = $AdminUser; password = $AdminPassword; grant_type = 'password'
}).access_token
$Headers = @{ Authorization = "Bearer $Token" }
$Instances = "$KeycloakUrl/admin/realms/$Realm/identity-provider/instances"
$Body = [Text.Encoding]::UTF8.GetBytes(($Provider | ConvertTo-Json -Depth 5))

$Exists = @(Invoke-RestMethod -Uri $Instances -Headers $Headers | Where-Object { $_.alias -eq $Alias }).Count -gt 0
if ($Exists) {
  Invoke-RestMethod -Method Put -Uri "$Instances/$Alias" -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' updated."
} else {
  Invoke-RestMethod -Method Post -Uri $Instances -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' created."
}
Write-Host "Valid OAuth redirect URI to register in Facebook Login: $KeycloakUrl/realms/$Realm/broker/$Alias/endpoint"
