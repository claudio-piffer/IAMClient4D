<#
  Creates or updates the Microsoft identity provider (personal Microsoft accounts by default; Keycloak
  provider 'microsoft', Microsoft Graph profile) in the Keycloak of the samples (Docker/) (Admin REST API),
  with the same config as TIAM4DMicrosoftIdPBuilder. The provider stays in the database of Docker/ until
  delete-volumes. For the test Keycloak (tests/IdentityProvider/docker, database in memory) run it after
  every up.cmd with -KeycloakUrl http://localhost:18080 -Realm iam4d-sample -AdminPassword admin. For work
  accounts use entra.ps1 (OpenID Connect, id_token checked).

  Microsoft Entra admin center, App registrations > New registration: supported account types matching -Tenant
  (default consumers: "Personal Microsoft accounts only"), redirect URI of platform Web
  {KeycloakUrl}/realms/{Realm}/broker/{Alias}/endpoint (default
  http://localhost:18180/auth/realms/iamclient4d/broker/microsoft/endpoint; Microsoft accepts http for localhost),
  then Certificates & secrets > New client secret (the Value, not the Secret ID).

  Client ID and secret: parameters, otherwise MICROSOFT_CLIENT_ID, MICROSOFT_CLIENT_SECRET, otherwise asked
  (the secret without echo).

  Example:
    powershell -ExecutionPolicy Bypass -File microsoft.ps1 -ClientId <application-id>
#>
param(
  [string]$ClientId = $env:MICROSOFT_CLIENT_ID,
  [string]$ClientSecret = $env:MICROSOFT_CLIENT_SECRET,
  [string]$KeycloakUrl = $(if ($env:KC_PORT) { "http://localhost:$env:KC_PORT/auth" } else { 'http://localhost:18180/auth' }),
  [string]$Realm = 'iamclient4d',
  [string]$AdminUser = 'admin',
  # Default: the password generated by Docker/setup-secrets
  [string]$AdminPassword = $(Get-Content -Raw -ErrorAction SilentlyContinue (Join-Path $PSScriptRoot '../secrets/kc_admin_password.txt')),
  [string]$Alias = 'microsoft',
  [string]$DisplayName = 'Microsoft',
  # consumers (personal accounts), common, organizations or a directory ID
  [string]$Tenant = 'consumers',
  # Prompt sent to Microsoft, e.g. select_account
  [string]$Prompt = '',
  # Emails from Microsoft considered verified: only with a directory ID as tenant (nOAuth)
  [switch]$TrustEmail,
  # Reachable only through kc_idp_hint
  [switch]$HideOnLogin
)
$ErrorActionPreference = 'Stop'

if (-not $ClientId) { $ClientId = Read-Host 'Client ID' }
if (-not $ClientSecret) {
  $LSecure = Read-Host 'Client secret' -AsSecureString
  $ClientSecret = [Runtime.InteropServices.Marshal]::PtrToStringBSTR(
    [Runtime.InteropServices.Marshal]::SecureStringToBSTR($LSecure))
}
$ClientId = $ClientId.Trim()
if (-not $ClientId -or -not $ClientSecret) { throw 'Client ID and client secret are required' }
if ($Alias -notmatch '^[A-Za-z0-9._\-]+$') { throw "Invalid alias '$Alias'" }
$Tenant = $Tenant.Trim()
if ($Tenant -notmatch '^[A-Za-z0-9.\-]+$') { throw "Invalid tenant '$Tenant'" }
# Same check as TIAM4DMicrosoftIdPBuilder.Build: Keycloak takes the Graph email without any check
if ($TrustEmail -and $Tenant -notmatch '^[0-9a-fA-F]{8}-([0-9a-fA-F]{4}-){3}[0-9a-fA-F]{12}$') {
  throw "-TrustEmail requires the directory ID (GUID) as tenant, not '$Tenant'"
}

$Config = [ordered]@{
  clientId     = $ClientId
  clientSecret = $ClientSecret
  tenantId     = $Tenant
  defaultScope = 'User.Read'
  pkceEnabled  = 'true'
  pkceMethod   = 'S256'
  syncMode     = 'IMPORT'
  hideOnLogin  = $HideOnLogin.IsPresent.ToString().ToLower()
}
if ($Prompt) { $Config.prompt = $Prompt.Trim() }

$Provider = [ordered]@{
  alias       = $Alias
  displayName = $DisplayName
  providerId  = 'microsoft'
  enabled     = $true
  trustEmail  = $TrustEmail.IsPresent
  hideOnLogin = $HideOnLogin.IsPresent
  config      = $Config
}

$Token = (Invoke-RestMethod -Method Post -Uri "$KeycloakUrl/realms/master/protocol/openid-connect/token" -Body @{
  client_id = 'admin-cli'; username = $AdminUser; password = $AdminPassword; grant_type = 'password'
}).access_token
$Headers = @{ Authorization = "Bearer $Token" }
$Instances = "$KeycloakUrl/admin/realms/$Realm/identity-provider/instances"
$Body = [Text.Encoding]::UTF8.GetBytes(($Provider | ConvertTo-Json -Depth 5))

$Exists = @(Invoke-RestMethod -Uri $Instances -Headers $Headers | Where-Object { $_.alias -eq $Alias }).Count -gt 0
if ($Exists) {
  Invoke-RestMethod -Method Put -Uri "$Instances/$Alias" -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' updated."
} else {
  Invoke-RestMethod -Method Post -Uri $Instances -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' created."
}
Write-Host "Redirect URI to register in Microsoft Entra (platform Web): $KeycloakUrl/realms/$Realm/broker/$Alias/endpoint"
