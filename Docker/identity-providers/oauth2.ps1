<#
  Creates or updates a generic OAuth 2.0 identity provider (no OpenID Connect: the user profile comes from
  the user info endpoint) in the Keycloak of the samples (Docker/) (Admin REST API), with the same config as
  TIAM4DOAuth2IdPBuilder. The provider stays in the database of Docker/ until delete-volumes. For the test
  Keycloak (tests/IdentityProvider/docker, database in memory) run it after every up.cmd with -KeycloakUrl
  http://localhost:18080 -Realm iam4d-sample -AdminPassword admin.

  Register a confidential client at the provider with redirect URI {KeycloakUrl}/realms/{Realm}/broker/{Alias}/endpoint
  (default http://localhost:18180/auth/realms/iamclient4d/broker/oauth2/endpoint). The user info endpoint must answer
  JSON; name its fields with -UserIdClaim, -UserNameClaim, -EmailClaim (dot notation for nested ones) when they
  are not sub, preferred_username and email.

  Endpoints, client ID and secret: parameters, otherwise OAUTH2_AUTHORIZATION_URL, OAUTH2_TOKEN_URL,
  OAUTH2_USERINFO_URL, OAUTH2_CLIENT_ID, OAUTH2_CLIENT_SECRET, otherwise asked (the secret without echo).

  Example (Strava):
    powershell -ExecutionPolicy Bypass -File oauth2.ps1 -Alias strava -AuthorizationUrl https://www.strava.com/oauth/authorize `
      -TokenUrl https://www.strava.com/oauth/token -UserInfoUrl https://www.strava.com/api/v3/athlete `
      -UserIdClaim id -UserNameClaim username -Scope read -ClientId <client-id>
#>
param(
  [string]$AuthorizationUrl = $env:OAUTH2_AUTHORIZATION_URL,
  [string]$TokenUrl = $env:OAUTH2_TOKEN_URL,
  [string]$UserInfoUrl = $env:OAUTH2_USERINFO_URL,
  [string]$ClientId = $env:OAUTH2_CLIENT_ID,
  [string]$ClientSecret = $env:OAUTH2_CLIENT_SECRET,
  [string]$KeycloakUrl = $(if ($env:KC_PORT) { "http://localhost:$env:KC_PORT/auth" } else { 'http://localhost:18180/auth' }),
  [string]$Realm = 'iamclient4d',
  [string]$AdminUser = 'admin',
  # Default: the password generated by Docker/setup-secrets
  [string]$AdminPassword = $(Get-Content -Raw -ErrorAction SilentlyContinue (Join-Path $PSScriptRoot '../secrets/kc_admin_password.txt')),
  [string]$Alias = 'oauth2',
  [string]$DisplayName = '',
  # Scopes of the provider; none by default
  [string[]]$Scope = @(),
  # Fields of the user info response; empty: Keycloak default (sub, preferred_username, email)
  [string]$UserIdClaim = '',
  [string]$UserNameClaim = '',
  [string]$EmailClaim = '',
  # Client authentication at the token endpoint
  [ValidateSet('client_secret_post', 'client_secret_basic')]
  [string]$ClientAuthMethod = 'client_secret_post',
  # For providers that reject code_challenge
  [switch]$NoPkce,
  # Emails from the provider considered verified: only if the provider verifies them
  [switch]$TrustEmail,
  # Reachable only through kc_idp_hint
  [switch]$HideOnLogin
)
$ErrorActionPreference = 'Stop'

if (-not $AuthorizationUrl) { $AuthorizationUrl = Read-Host 'Authorization URL' }
if (-not $TokenUrl) { $TokenUrl = Read-Host 'Token URL' }
if (-not $UserInfoUrl) { $UserInfoUrl = Read-Host 'User info URL' }
if (-not $ClientId) { $ClientId = Read-Host 'Client ID' }
if (-not $ClientSecret) {
  $LSecure = Read-Host 'Client secret' -AsSecureString
  $ClientSecret = [Runtime.InteropServices.Marshal]::PtrToStringBSTR(
    [Runtime.InteropServices.Marshal]::SecureStringToBSTR($LSecure))
}
$ClientId = $ClientId.Trim()
if (-not $ClientId -or -not $ClientSecret) { throw 'Client ID and client secret are required' }
if ($Alias -notmatch '^[A-Za-z0-9._\-]+$') { throw "Invalid alias '$Alias'" }
# Same check as TIAM4DOAuth2IdPBuilder.Build: the profile comes only from the user info endpoint
foreach ($U in $AuthorizationUrl, $TokenUrl, $UserInfoUrl) { if (-not $U -or -not $U.Trim()) { throw 'Authorization, token and user info URLs are required' } }

$Config = [ordered]@{
  authorizationUrl = $AuthorizationUrl.Trim()
  tokenUrl         = $TokenUrl.Trim()
  userInfoUrl      = $UserInfoUrl.Trim()
  clientId         = $ClientId
  clientSecret     = $ClientSecret
  clientAuthMethod = $ClientAuthMethod
  pkceEnabled      = (-not $NoPkce.IsPresent).ToString().ToLower()
  syncMode         = 'IMPORT'
  hideOnLogin      = $HideOnLogin.IsPresent.ToString().ToLower()
}
if (-not $NoPkce) { $Config.pkceMethod = 'S256' }
$Scopes = @($Scope | ForEach-Object { $_ -split '[ ,]' } | ForEach-Object { $_.Trim() } | Where-Object { $_ })
if ($Scopes.Count -gt 0) { $Config.defaultScope = $Scopes -join ' ' }
if ($UserIdClaim.Trim()) { $Config.userIDClaim = $UserIdClaim.Trim() }
if ($UserNameClaim.Trim()) { $Config.userNameClaim = $UserNameClaim.Trim() }
if ($EmailClaim.Trim()) { $Config.emailClaim = $EmailClaim.Trim() }

$Provider = [ordered]@{
  alias       = $Alias
  displayName = $DisplayName
  providerId  = 'oauth2'
  enabled     = $true
  trustEmail  = $TrustEmail.IsPresent
  hideOnLogin = $HideOnLogin.IsPresent
  config      = $Config
}

$Token = (Invoke-RestMethod -Method Post -Uri "$KeycloakUrl/realms/master/protocol/openid-connect/token" -Body @{
  client_id = 'admin-cli'; username = $AdminUser; password = $AdminPassword; grant_type = 'password'
}).access_token
$Headers = @{ Authorization = "Bearer $Token" }
$Instances = "$KeycloakUrl/admin/realms/$Realm/identity-provider/instances"
$Body = [Text.Encoding]::UTF8.GetBytes(($Provider | ConvertTo-Json -Depth 5))

$Exists = @(Invoke-RestMethod -Uri $Instances -Headers $Headers | Where-Object { $_.alias -eq $Alias }).Count -gt 0
if ($Exists) {
  Invoke-RestMethod -Method Put -Uri "$Instances/$Alias" -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' updated."
} else {
  Invoke-RestMethod -Method Post -Uri $Instances -Headers $Headers -ContentType 'application/json' -Body $Body | Out-Null
  Write-Host "Identity provider '$Alias' created."
}
Write-Host "Redirect URI to register at the provider: $KeycloakUrl/realms/$Realm/broker/$Alias/endpoint"
